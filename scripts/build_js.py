"""Generate the npm package's TypeScript sources from data/canonical.

Everything under `packages/js/src/{data,country,generated}` is written here and
gitignored -- the NDJSON is the single source of truth, and a generated file
checked into git is a copy waiting to drift.

Three decisions worth knowing before reading the code:

1. **Data is emitted as `JSON.parse(`...`)` inside a backtick literal**, not as
   a JS object literal and not as `.json`. JSON.parse of a string is faster for
   an engine to ingest than an equivalent object literal at these sizes, and it
   avoids import attributes (`with { type: 'json' }`), whose bundler support is
   still uneven -- Metro in particular. A backtick literal rather than a quoted
   one because JSON is full of `"` characters: quoting would escape every one
   of them and inflate the cities table by roughly 15%, while a backtick
   literal only has to escape the handful of backslashes.

2. **Every byte of data exists exactly once.** The all-cities table is not a
   second copy; `data/cities.all.js` concatenates the 250 per-country chunks.
   Same for states. That is what keeps the tarball from doubling.

3. **The Unicode tables are generated, not hand-ported.** `normalize_name`
   folds combining marks by Python's `unicodedata.combining` and detects a
   Cyrillic base by character *name*. JS has neither, and the near-equivalents
   (`\\p{M}`, `\\p{Script=Cyrillic}`) do not agree at the edges. Emitting the
   exact codepoint sets from the same Python that computed every
   `normalized_name` in the dataset makes the JS fold correct by construction
   rather than by resemblance.
"""

import argparse
import json
import os
import shutil
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from lib import schema_to_ts  # noqa: E402

CANONICAL = os.path.join(ROOT, "data", "canonical")
SCHEMA = os.path.join(ROOT, "schema")
PKG = os.path.join(ROOT, "packages", "js")
SRC = os.path.join(PKG, "src")

BANNER = "// Generated by scripts/build_js.py from data/canonical -- do not edit.\n"

# JSON, minified with sorted keys, exactly as the NDJSON carries it. Matching
# the Python side's separators keeps a JS-emitted row byte-identical to its
# NDJSON line, which the conformance test relies on.
DUMP = dict(ensure_ascii=False, separators=(",", ":"), sort_keys=True)


# --------------------------------------------------------------------- helpers


def read_ndjson(stem):
    path = os.path.join(CANONICAL, stem + ".ndjson")
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return len(text.encode("utf-8"))


def literal(value):
    """A JS backtick-literal holding `value` as JSON.

    Only three things are special inside a template literal: a backtick, a
    backslash, and the `${` interpolation opener. JSON's structural quotes need
    no escaping at all, which is the whole reason for using one.
    """
    payload = json.dumps(value, **DUMP)
    payload = payload.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    return "`" + payload + "`"


def data_module(name, value, type_expr, doc="", depth=1):
    """One ESM data module plus its declaration file.

    `depth` is how many directories below `src/` the module sits, because the
    declaration has to reach back up to `generated/types.js`. Getting this
    wrong is invisible at runtime -- the data still loads -- but it breaks
    every declaration under `data/co`, `data/s` and `data/c`, which is exactly
    the path a consumer takes when they import `geodata-js/country/NG`.
    """
    js = BANNER
    if doc:
        js += "// " + doc + "\n"
    js += "export const {} = /* @__PURE__ */ JSON.parse({});\n".format(name, literal(value))
    up = "../" * depth
    dts = BANNER + 'import type * as G from "{}generated/types.js";\n'.format(up)
    dts += "export declare const {}: {};\n".format(name, type_expr)
    return js, dts


# ------------------------------------------------------------- unicode tables


def _ranges(codepoints):
    out = []
    for cp in codepoints:
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def unicode_tables():
    """The exact codepoint sets `scripts/lib/normalize.py` behaves on.

    COMBINING mirrors `unicodedata.combining(ch) != 0` -- note this is the
    canonical combining *class*, not the general category: several `Mn`
    characters have class 0 and Python keeps them, while `\\p{M}` in JS would
    drop them.

    MARK_BEARING mirrors `unicodedata.name(ch).startswith("CYRILLIC")`, the
    script whose combining marks are letters rather than decoration.

    CASEFOLD carries only the delta where `str.casefold()` differs from
    `str.lower()` -- 297 codepoints, led by `ss` for `ss`. JS `toLowerCase()`
    agrees with Python `lower()` elsewhere, so applying this map first and
    lowercasing after reproduces `casefold()`.
    """
    combining, cyrillic, casefold = [], [], []
    for cp in range(0x110000):
        ch = chr(cp)
        if unicodedata.combining(ch):
            combining.append(cp)
        try:
            if unicodedata.name(ch).startswith("CYRILLIC"):
                cyrillic.append(cp)
        except ValueError:
            pass
        folded = ch.casefold()
        if folded != ch.lower():
            casefold.append((cp, folded))
    return _ranges(combining), _ranges(cyrillic), casefold


def emit_unicode_ts():
    combining, cyrillic, casefold = unicode_tables()

    def pack(rs):
        # "start:len" pairs in hex, one flat string: compact in source and in
        # the gzipped tarball, and parsed once at module load.
        return " ".join("{:x}:{:x}".format(a, b - a) for a, b in rs)

    fold = " ".join(
        "{:x}>{}".format(cp, "-".join("{:x}".format(ord(c)) for c in s))
        for cp, s in casefold
    )
    body = BANNER + '''
/**
 * Codepoint tables extracted from the same CPython Unicode database that
 * computed every `normalized_name` in data/canonical. See
 * scripts/build_js.py:unicode_tables for why these are generated rather than
 * approximated with \\p{{M}} and \\p{{Script=Cyrillic}}.
 */

/** Canonical combining class != 0. {ncomb} ranges. */
export const COMBINING = "{comb}";

/** Characters whose Unicode name begins with CYRILLIC. {ncyr} ranges. */
export const MARK_BEARING = "{cyr}";

/** casefold() where it differs from lower(). {nfold} entries. */
export const CASEFOLD_DELTA = "{fold}";
'''.format(
        comb=pack(combining), ncomb=len(combining),
        cyr=pack(cyrillic), ncyr=len(cyrillic),
        fold=fold, nfold=len(casefold),
    )
    return write(os.path.join(SRC, "generated", "unicode.ts"), body)


# --------------------------------------------------------------------- emitters


def emit_types():
    parts = [
        BANNER,
        "// Interfaces derived from schema/*.schema.json, the same contract the",
        "// Python dataclasses in src/geodata/types.py are checked against.",
        "// Field names are snake_case because that is the wire format: renaming",
        "// them would mean transforming 152,970 rows at load time.",
        "",
    ]
    for stem in ("country", "state", "city", "language", "region", "subregion"):
        parts.append(schema_to_ts.interface(schema_to_ts.load(SCHEMA, stem)))
        parts.append("")

    parts.append('''/** One entry of `Country["timezones"]`. */
export type Timezone = Country["timezones"][number];

/**
 * A territory's other identity, as a subdivision of another country.
 * Martinique is both country `MQ` and French subdivision `FR-MQ`; neither
 * representation is canonical.
 */
export type SubdivisionLink = NonNullable<Country["also_subdivision_of"]>;

/** A state plus its children, as returned by `stateTree`. */
export interface StateNode {
  state: State;
  children: StateNode[];
}

/** Translated names keyed by BCP-47 tag. */
export type Translations = Record<string, string>;
''')
    return write(os.path.join(SRC, "generated", "types.ts"), "\n".join(parts))


def emit_version(release, version):
    body = BANNER + '''
/**
 * The package version and the dataset version are deliberately separate.
 * `VERSION` moves for a code-only fix; `DATASET_VERSION` moves only when the
 * data does. CI asserts both against data/RELEASE.json, and the Python wheel
 * carries the identical pair -- that is guarantee 1 of the multi-stack plan.
 */
export const VERSION = {version};
export const DATASET_VERSION = {dataset};
export const SOURCE_TAG = {tag};
export const SOURCE_REPO = {repo};

export const COUNTS = {counts} as const;
'''.format(
        version=json.dumps(version),
        dataset=json.dumps(release["version"]),
        tag=json.dumps(release["source"]["tag"]),
        repo=json.dumps(release["source"]["repo"]),
        counts=json.dumps(release["counts"], sort_keys=True, indent=2),
    )
    return write(os.path.join(SRC, "generated", "version.ts"), body)


def emit_manifest(codes, states_by, cities_by):
    body = BANNER + '''
/** Every ISO 3166-1 alpha-2 code in the dataset, sorted. */
export const COUNTRY_CODES = {codes} as const;

/**
 * The literal union of shippable codes. `import("geodata-js/country/NG")`
 * type-checks; a typo does not.
 */
export type CountryCode = (typeof COUNTRY_CODES)[number];

/** Row counts per country, for sizing a lazy load before making it. */
export const COUNTS_BY_COUNTRY: Record<string, {{ states: number; cities: number }}> =
  /* @__PURE__ */ JSON.parse({counts});
'''.format(
        codes=json.dumps(codes, indent=2),
        counts=literal(
            {c: {"states": states_by.get(c, 0), "cities": cities_by.get(c, 0)} for c in codes}
        ),
    )
    return write(os.path.join(SRC, "generated", "manifest.ts"), body)


def emit_lazy(codes):
    """Static per-country dynamic imports: one map per table, one FILE per map.

    Three maps rather than one, because a subdivision dropdown must not pay for
    city data. `statesOf("US")` through STATES costs about 10 KB gzipped; the
    same query through CHUNKS would drag in 16,731 US cities and cost 481 KB.

    Three *files* rather than one module, because of how bundlers treat
    `import()`. A dynamic import is a code-splitting instruction: webpack emits
    a chunk file for every one it can see in the graph, whether or not the
    surrounding export is ever used. With all three maps in a single module,
    anything importing STATES put CITIES' 250 `import()` sites in the graph
    too -- a Next.js client component that only builds a state dropdown emitted
    43 MB of city chunks it would never fetch. Splitting the maps lets
    `sideEffects: false` tree-shaking drop the cities module entirely when
    `citiesOf` is unused, and the chunks with it.

    Deliberately not `import(`../data/s/${code}.js`)`: a template specifier
    forces every bundler to guess the match set, and Metro (React Native)
    cannot resolve one at all. 250 explicit arrow functions per map are boring,
    work everywhere, and let a bundler emit one chunk per country per table.
    """
    written = {}

    types = [
        BANNER,
        'import type { City, Country, State } from "./types.js";',
        "",
        "/** One country's row, subdivisions and cities. */",
        "export interface CountryChunk {",
        "  country: Country;",
        "  states: State[];",
        "  cities: City[];",
        "}",
        "",
        "/** Subdivisions of one country. */",
        "export type StateChunk = { states: State[] };",
        "",
        "/** Cities of one country. */",
        "export type CityChunk = { cities: City[] };",
        "",
    ]
    written["lazy.ts"] = write(
        os.path.join(SRC, "generated", "lazy.ts"), "\n".join(types)
    )

    maps = (
        (
            "lazy.countries.ts",
            "CHUNKS",
            "CountryChunk",
            "../country/{}.js",
            "Everything about one country -- row, subdivisions and cities. The\n"
            " * heaviest of the three; prefer STATES or CITIES unless you want all of it.",
        ),
        (
            "lazy.states.ts",
            "STATES",
            "StateChunk",
            "../data/s/{}.js",
            "Subdivisions only -- what a cascading dropdown's first tier needs.",
        ),
        (
            "lazy.cities.ts",
            "CITIES",
            "CityChunk",
            "../data/c/{}.js",
            "Cities only -- the second tier, once a subdivision is chosen.\n"
            " * Reached through a dynamic import so that a consumer who never calls\n"
            " * `citiesOf` does not have 250 city chunks emitted into their build.",
        ),
    )
    for filename, name, chunk_type, template, doc in maps:
        lines = [
            BANNER,
            'import type {{ {} }} from "./lazy.js";'.format(chunk_type),
            "",
            "/** {} */".format(doc),
            "export const {}: Record<string, () => Promise<{}>> = {{".format(name, chunk_type),
        ]
        for code in codes:
            lines.append('  {}: () => import("{}"),'.format(code, template.format(code)))
        lines += ["};", ""]
        written[filename] = write(os.path.join(SRC, "generated", filename), "\n".join(lines))

    return written


def emit_country_entries(countries, states_by, cities_by):
    total = 0
    for country in countries:
        code = country["iso2"]
        js, dts = data_module(
            "country", country, "G.Country", "The {} row.".format(code), depth=2
        )
        total += write(os.path.join(SRC, "data", "co", code + ".js"), js)
        total += write(os.path.join(SRC, "data", "co", code + ".d.ts"), dts)

        js, dts = data_module(
            "states", states_by.get(code, []), "G.State[]",
            "{} subdivisions of {}, all depths.".format(len(states_by.get(code, [])), code),
            depth=2,
        )
        total += write(os.path.join(SRC, "data", "s", code + ".js"), js)
        total += write(os.path.join(SRC, "data", "s", code + ".d.ts"), dts)

        js, dts = data_module(
            "cities", cities_by.get(code, []), "G.City[]",
            "{} cities in {}.".format(len(cities_by.get(code, [])), code),
            depth=2,
        )
        total += write(os.path.join(SRC, "data", "c", code + ".js"), js)
        total += write(os.path.join(SRC, "data", "c", code + ".d.ts"), dts)

        entry = BANNER + '''// Subpath entry: `import {{ states }} from "geodata-js/country/{code}"`.
// Everything {code} needs and nothing else -- the point of this subpath is that
// importing it can never reach the other 249 countries' cities.
import type {{ City, Country, State }} from "../generated/types.js";
import {{ country as _country }} from "../data/co/{code}.js";
import {{ states as _states }} from "../data/s/{code}.js";
import {{ cities as _cities }} from "../data/c/{code}.js";

export const country: Country = _country;
export const states: State[] = _states;
export const cities: City[] = _cities;

export default {{ country, states, cities }};
'''.format(code=code)
        total += write(os.path.join(SRC, "country", code + ".ts"), entry)
    return total


def emit_aggregates(codes):
    """The all-states and all-cities tables, assembled from the chunks.

    `concat` rather than a spread: spreading 152,970 elements into a literal
    blows the argument limit in some engines.
    """
    total = 0
    for kind, folder, name in (("states", "s", "State"), ("cities", "c", "City")):
        lines = [BANNER,
                 "// Assembled from the 250 per-country chunks so the dataset is",
                 "// stored exactly once. Order is by country code, then chunk order."]
        for code in codes:
            lines.append('import {{ {k} as _{c} }} from "./{f}/{c}.js";'.format(
                k=kind, c=code, f=folder))
        lines.append("")
        lines.append("export const {} = [].concat({});".format(
            kind, ", ".join("_" + c for c in codes)))
        lines.append("")
        total += write(os.path.join(SRC, "data", kind + ".all.js"), "\n".join(lines))

        dts = (BANNER + 'import type * as G from "../generated/types.js";\n'
               + "export declare const {}: G.{}[];\n".format(kind, name))
        total += write(os.path.join(SRC, "data", kind + ".all.d.ts"), dts)
    return total


# ------------------------------------------------------------------------ main


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", help="npm package version; default from package.json")
    ap.add_argument("--clean", action="store_true", help="wipe generated dirs first")
    args = ap.parse_args()

    with open(os.path.join(ROOT, "data", "RELEASE.json"), encoding="utf-8") as fh:
        release = json.load(fh)

    version = args.version
    if version is None:
        with open(os.path.join(PKG, "package.json"), encoding="utf-8") as fh:
            version = json.load(fh)["version"]

    if args.clean:
        for sub in ("data", "country", "generated"):
            shutil.rmtree(os.path.join(SRC, sub), ignore_errors=True)

    countries = read_ndjson("countries")
    states = read_ndjson("states")
    cities = read_ndjson("cities")
    languages = read_ndjson("languages")
    regions = read_ndjson("regions")
    subregions = read_ndjson("subregions")
    tr_countries = read_ndjson("translations.countries")
    tr_states = read_ndjson("translations.states")

    codes = sorted(c["iso2"] for c in countries)
    countries.sort(key=lambda c: c["iso2"])

    states_by, cities_by = {}, {}
    for s in states:
        states_by.setdefault(s["country_iso2"], []).append(s)
    for c in cities:
        cities_by.setdefault(c["country_iso2"], []).append(c)

    written = {}
    written["types.ts"] = emit_types()
    written["version.ts"] = emit_version(release, version)
    written["unicode.ts"] = emit_unicode_ts()
    written["manifest.ts"] = emit_manifest(
        codes,
        {k: len(v) for k, v in states_by.items()},
        {k: len(v) for k, v in cities_by.items()},
    )
    written.update(emit_lazy(codes))

    for name, rows, type_expr, doc in (
        ("countries", countries, "G.Country[]", "All 250 countries."),
        ("languages", languages, "G.Language[]", "The ISO 639 table."),
        ("regions", regions, "G.Region[]", ""),
        ("subregions", subregions, "G.Subregion[]", ""),
    ):
        js, dts = data_module(name, rows, type_expr, doc)
        written[name + ".js"] = write(os.path.join(SRC, "data", name + ".js"), js)
        write(os.path.join(SRC, "data", name + ".d.ts"), dts)

    # Translations collapse to a plain lookup: the array shape is a storage
    # detail of NDJSON, and every caller wants the map.
    js, dts = data_module(
        "countryTranslations",
        {r["iso2"]: r["translations"] for r in tr_countries},
        "Record<string, G.Translations>",
        "iso2 -> {locale: name}.",
    )
    written["translations.countries.js"] = write(
        os.path.join(SRC, "data", "translations.countries.js"), js)
    write(os.path.join(SRC, "data", "translations.countries.d.ts"), dts)

    js, dts = data_module(
        "stateTranslations",
        {str(r["state_id"]): r["translations"] for r in tr_states},
        "Record<string, G.Translations>",
        "state id (as a string key) -> {locale: name}.",
    )
    written["translations.states.js"] = write(
        os.path.join(SRC, "data", "translations.states.js"), js)
    write(os.path.join(SRC, "data", "translations.states.d.ts"), dts)

    written["country/*"] = emit_country_entries(countries, states_by, cities_by)
    written["*.all.js"] = emit_aggregates(codes)

    # The same gate the Python side has: a generator that silently drops rows
    # is worse than one that crashes.
    actual = {"countries": len(countries), "states": len(states), "cities": len(cities)}
    if actual != release["counts"]:
        raise SystemExit(
            "count mismatch vs data/RELEASE.json:\n  expected {}\n  got      {}".format(
                release["counts"], actual))

    print("geodata-js {} (dataset {})".format(version, release["version"]))
    for key in sorted(written):
        print("  {:<28} {:>10,} bytes".format(key, written[key]))
    print("  {:<28} {:>10,} bytes total".format("", sum(written.values())))
    print("counts OK: {countries} countries / {states} states / {cities} cities".format(**actual))


if __name__ == "__main__":
    main()
