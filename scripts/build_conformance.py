#!/usr/bin/env python3
"""Emit tests/conformance/cases.json from data/canonical.

The cases are derived from the NDJSON, not from either implementation. That is
the point: a suite generated by running the Python API would only prove the JS
port agrees with Python, including where Python is wrong. Reading the canonical
rows directly makes both languages answerable to the data.

Deterministic -- same input, byte-identical output -- so CI can assert the file
committed matches a rebuild.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CANON = os.path.join(ROOT, "data", "canonical")
OUT = os.path.join(ROOT, "tests", "conformance", "cases.json")

# A spread chosen for the shapes that break implementations, not for size:
# nested subdivisions (GB), a re-parented cities table (FR), a multi-level
# territory (MQ), non-Latin names (RU, CN), a country with no subdivisions
# upstream (VA), and the one whose ids churned most (US).
COUNTRIES = ["NG", "GB", "FR", "MQ", "US", "DE", "BR", "RU", "CN", "IN", "ES", "BE", "VA", "PR"]


def read(name):
    with open(os.path.join(CANON, name), encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def main():
    countries = {c["iso2"]: c for c in read("countries.ndjson")}
    states = read("states.ndjson")
    cities = read("cities.ndjson")
    languages = read("languages.ndjson")
    ctrans = {t["iso2"]: t["translations"] for t in read("translations.countries.ndjson")}

    states_by_country = {}
    for s in states:
        states_by_country.setdefault(s["country_iso2"], []).append(s)
    cities_by_state = {}
    for c in cities:
        cities_by_state.setdefault(c["state_id"], []).append(c)

    cases = []

    def add(fn, args, expect):
        cases.append({"fn": fn, "args": args, "expect": expect})

    for iso2 in COUNTRIES:
        c = countries[iso2]
        rows = sorted(states_by_country.get(iso2, []), key=lambda s: s["name"])

        # Country resolution, through every accepted key form.
        for key in [iso2, iso2.lower(), c["iso3"], c["name"]]:
            if key:
                add("getCountry", [key], {"iso2": iso2, "name": c["name"]})

        add("statesOf", [iso2], {"count": len(rows)})
        add("rootStates", [iso2], {
            "count": len([s for s in rows if s["depth"] == 1]),
            "names": [s["name"] for s in rows if s["depth"] == 1][:8],
        })

        # State lookup by the preferred join key, and by name.
        with_iso = [s for s in rows if s.get("iso3166_2")]
        if with_iso:
            s = with_iso[len(with_iso) // 2]
            add("getState", [iso2, s["iso3166_2"]], {"iso3166_2": s["iso3166_2"], "name": s["name"]})
            # The bare subdivision code must resolve the same row: a UI that has
            # only "BIR" should not have to know the country prefix.
            bare = s["iso3166_2"].split("-", 1)[1]
            add("getState", [iso2, bare], {"iso3166_2": s["iso3166_2"]})
            add("getStateByName", [iso2, s["name"]], {"iso3166_2": s["iso3166_2"]})

        # Cities, scoped to a subdivision that actually has some.
        populated = [s for s in rows if cities_by_state.get(s["id"])]
        if populated:
            s = populated[len(populated) // 2]
            got = sorted(cities_by_state[s["id"]], key=lambda x: x["name"])
            key = s.get("iso3166_2") or s["name"]
            add("citiesOf", [iso2, key], {"count": len(got), "first": got[0]["name"]})
            add("searchCities", [got[0]["name"], iso2, 1], {"first": got[0]["name"]})

        if iso2 in ctrans:
            for locale in ("fr", "de", "ja", "ru"):
                if locale in ctrans[iso2]:
                    add("localizedName", [iso2, locale], {"name": ctrans[iso2][locale]})

        if c.get("also_subdivision_of"):
            twin_id = c["also_subdivision_of"]["state_id"]
            twin = next(s for s in states if s["id"] == twin_id)
            add("subdivisionTwin", [iso2], {
                "country_iso2": twin["country_iso2"],
                "iso3166_2": twin.get("iso3166_2"),
            })
        else:
            add("subdivisionTwin", [iso2], None)

    # Languages: the code is the identity, so these assertions are stable across
    # dataset versions in a way none of the above are.
    by_code = {l["code"]: l for l in languages}
    for code in ("pt", "zh", "ar", "en", "sw"):
        if code in by_code:
            add("getLanguage", [code], {"code": code, "name": by_code[code]["name"]})
            add("getLanguage", [code + "-XX"], {"code": code})
    add("languageCounts", [], {
        "total": len(languages),
        "iso639_1": len([l for l in languages if l["standard"] == "iso639_1"]),
        "iso639_2": len([l for l in languages if l["standard"] == "iso639_2"]),
    })

    # The fold, over real dataset names in five scripts.
    sample = [c["name"] for c in list(countries.values())[:20]]
    sample += [s["name"] for s in states[::701]][:20]
    for name in sample:
        row = next((x for x in states if x["name"] == name), None)
        expected = row["normalized_name"] if row else countries[
            next(k for k, v in countries.items() if v["name"] == name)
        ]["normalized_name"]
        add("normalizeName", [name], {"out": expected})

    payload = {
        "_note": (
            "Generated by scripts/build_conformance.py from data/canonical. "
            "Run by tests/test_conformance.py and packages/js/test/conformance.test.ts. "
            "Expectations come from the NDJSON, not from either implementation."
        ),
        "dataset_version": json.load(open(os.path.join(ROOT, "data", "RELEASE.json")))["version"],
        "cases": cases,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=1, sort_keys=True)
        fh.write("\n")
    print("wrote {} cases to {}".format(len(cases), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    sys.exit(main())
